//! build.rs — 自动发现策略模块（模板冻结）
//!
//! 扫描 `src/*.rs`（排除 `lib.rs`、`registry.rs`），生成
//! `OUT_DIR/strategy_registry_gen.rs`：
//!
//! ```text
//! pub mod sar_snt3;
//! pub mod my_strat;
//! fn generated_factories() -> &'static [StrategyEntry] {
//!     &[ sar_snt3::__strategy_entry(), my_strat::__strategy_entry(), ... ]
//! }
//! ```
//!
//! 新增策略 = 往 `src/` 放一个 `.rs` 文件（尾部调用 `register_strategy!`），
//! 无需修改任何其他文件。下次 `cargo build` 自动编入注册表。

use std::fs;
use std::path::Path;

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=src");

    let src = Path::new("src");
    let mut files: Vec<String> = fs::read_dir(src)
        .expect("build.rs: 读 src 目录失败")
        .filter_map(|e| e.ok())
        .filter(|e| e.file_type().map(|t| t.is_file()).unwrap_or(false))
        .filter_map(|e| {
            let name = e.file_name().to_string_lossy().to_string();
            name.ends_with(".rs").then_some(name)
        })
        .filter(|n| n != "lib.rs" && n != "registry.rs")
        .collect();
    files.sort(); // 确定性：模块清单与注册表顺序稳定

    let manifest_dir = std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR 未设置");

    let mut gen = String::new();
    gen.push_str("// @generated by build.rs — do not edit\n");
    for f in &files {
        let module = f.trim_end_matches(".rs");
        // include! 内声明的 mod 相对被包含文件目录解析，需 #[path] 指回 src/
        gen.push_str(&format!(
            "#[path = r#\"{manifest_dir}/src/{f}\"#]\npub mod {module};\n"
        ));
    }
    gen.push_str(
        "\nfn generated_factories() -> Vec<crate::registry::StrategyEntry> {\n    vec![\n",
    );
    for f in &files {
        let module = f.trim_end_matches(".rs");
        gen.push_str(&format!("        {module}::__strategy_entry(),\n"));
    }
    gen.push_str("    ]\n}\n");

    let out = std::env::var("OUT_DIR").expect("OUT_DIR 未设置");
    let out_path = Path::new(&out).join("strategy_registry_gen.rs");
    fs::write(&out_path, gen).expect("build.rs: 写生成文件失败");
}
